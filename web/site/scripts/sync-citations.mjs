/**
 * Emit public/scripts/factor-citations.js from data/factors.json so the
 * calculator can import citation labels without dumping JSON into HTML.
 */
import { writeFileSync, mkdirSync, readFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const SITE = path.resolve(HERE, '..');
const REPO = path.resolve(SITE, '../..');

const { citationIndex } = await import(
  pathToFileURL(path.join(SITE, 'src/lib/citations.js')).href
);

const factors = JSON.parse(
  readFileSync(path.join(REPO, 'data/factors.json'), 'utf8'),
).factors;
const index = citationIndex(factors);
const outDir = path.join(SITE, 'public/scripts');
mkdirSync(outDir, { recursive: true });
const outPath = path.join(outDir, 'factor-citations.js');
const body = `/** Generated by scripts/sync-citations.mjs. Do not edit. */\nexport default ${JSON.stringify(index, null, 2)};\n`;
writeFileSync(outPath, body);
process.stdout.write(`wrote ${path.relative(SITE, outPath)} (${Object.keys(index).length} factors)\n`);
